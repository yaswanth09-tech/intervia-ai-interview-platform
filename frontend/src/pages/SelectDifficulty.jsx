import { useState } from 'react'
import { useNavigate, useSearchParams } from 'react-router-dom'
import DashboardHeader from '../components/DashboardHeader'
import api from '../api/axios'

const LEVELS = [
  {
    id: 'easy',
    title: 'Easy',
    subtitle: 'Beginner & Entry-level concepts',
    mcq: 5,
    descriptive: 5,
    badge: 'Standard',
  },
  {
    id: 'medium',
    title: 'Medium',
    subtitle: 'Mid-level technical depth & practical scenarios',
    mcq: 10,
    descriptive: 5,
    badge: 'Recommended',
  },
  {
    id: 'hard',
    title: 'Hard',
    subtitle: 'Senior & advanced architectural challenges',
    mcq: 15,
    descriptive: 10,
    badge: 'Advanced',
  },
]

export default function SelectDifficulty() {
  const navigate = useNavigate()
  const [searchParams] = useSearchParams()
  const resumeId = searchParams.get('resume_id')

  const [selected, setSelected] = useState('medium')
  const [generating, setGenerating] = useState(false)
  const [error, setError] = useState('')

  async function handleStart() {
    if (!resumeId) {
      setError('Missing resume reference. Please upload your resume first.')
      return
    }

    setGenerating(true)
    setError('')
    try {
      const res = await api.post('/interview/generate-questions', {
        resume_id: resumeId,
        difficulty: selected,
      })
      const sessionId = res.data.session_id
      navigate(`/interview/mcq?session_id=${sessionId}`)
    } catch (err) {
      setError(err.response?.data?.detail || 'Failed to generate interview questions. Please try again.')
    } finally {
      setGenerating(false)
    }
  }

  return (
    <div className="relative min-h-screen overflow-x-hidden bg-gradient-to-br from-[#0a0d20] via-[#0b0a1f] to-[#150a28] font-sans">
      {/* continuous grid + ambient glows, same treatment as Dashboard/Login */}
      <div
        className="pointer-events-none fixed inset-0 z-0 opacity-[0.04]"
        style={{
          backgroundImage:
            'linear-gradient(#fff 1px, transparent 1px), linear-gradient(90deg, #fff 1px, transparent 1px)',
          backgroundSize: '46px 46px',
          maskImage: 'linear-gradient(to bottom, transparent, black 10%, black 90%, transparent)',
        }}
      />
      <div className="pointer-events-none fixed -top-32 right-0 h-[28rem] w-[28rem] rounded-full bg-violet-600/15 blur-[130px]" />
      <div className="pointer-events-none fixed bottom-0 left-0 h-96 w-96 rounded-full bg-blue-600/10 blur-[130px]" />

      <div className="relative z-10">
        <DashboardHeader />

        <main className="mx-auto max-w-3xl px-6 py-12">
          <h1 className="text-2xl font-bold tracking-tight text-white">Choose Difficulty Level</h1>
          <p className="mt-1.5 text-sm text-white/50">
            Select the intensity of your mock interview. Questions will be dynamically generated by AI
            based on your uploaded resume.
          </p>

          {error && (
            <div className="mt-6 rounded-xl border border-red-400/25 bg-red-500/10 p-4 text-sm text-red-200">
              {error}
            </div>
          )}

          <div className="mt-8 space-y-4">
            {LEVELS.map((level) => {
              const isSelected = selected === level.id
              return (
                <div
                  key={level.id}
                  onClick={() => setSelected(level.id)}
                  className={`cursor-pointer rounded-2xl border p-6 backdrop-blur-xl transition ${
                    isSelected
                      ? 'border-violet-400/40 bg-violet-500/[0.08] shadow-[0_20px_50px_-25px_rgba(76,29,149,0.6)]'
                      : 'border-white/10 bg-white/[0.035] hover:border-white/20'
                  }`}
                >
                  <div className="flex items-center justify-between">
                    <div className="flex items-center gap-3">
                      <div
                        className={`flex h-5 w-5 items-center justify-center rounded-full border transition ${
                          isSelected
                            ? 'border-transparent bg-gradient-to-br from-violet-500 to-blue-500 shadow-[0_0_12px_rgba(139,92,246,0.6)]'
                            : 'border-white/20'
                        }`}
                      >
                        {isSelected && <div className="h-2 w-2 rounded-full bg-white" />}
                      </div>
                      <h3 className="text-lg font-semibold text-white">{level.title}</h3>
                      <span className="rounded border border-white/10 bg-white/[0.05] px-2 py-0.5 text-xs font-medium text-white/50">
                        {level.badge}
                      </span>
                    </div>
                    <div className="text-right text-xs text-white/45">
                      <span className="font-semibold text-white/80">{level.mcq}</span> MCQs •{' '}
                      <span className="font-semibold text-white/80">{level.descriptive}</span> Descriptive
                    </div>
                  </div>

                  <p className="mt-2 pl-8 text-sm text-white/55">{level.subtitle}</p>
                </div>
              )
            })}
          </div>

          <div className="mt-10 flex items-center justify-between">
            <button
              onClick={() => navigate('/interview/new')}
              className="rounded-lg border border-white/10 bg-white/[0.04] px-4 py-2 text-sm font-medium text-white/80 transition hover:border-white/20 hover:bg-white/[0.07]"
            >
              ← Back to Resume
            </button>
            <button
              onClick={handleStart}
              disabled={generating}
              className="rounded-lg bg-gradient-to-r from-violet-500 via-purple-500 to-blue-500 px-6 py-2.5 text-sm font-semibold text-white shadow-[0_10px_30px_-10px_rgba(124,58,237,0.6)] transition hover:brightness-110 disabled:opacity-50"
            >
              {generating ? 'Generating Questions with AI…' : 'Generate & Start Interview →'}
            </button>
          </div>
        </main>
      </div>
    </div>
  )
}