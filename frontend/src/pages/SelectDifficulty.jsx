import { useState } from 'react'
import { useNavigate, useSearchParams } from 'react-router-dom'
import DashboardHeader from '../components/DashboardHeader'
import api from '../api/axios'

const LEVELS = [
  {
    id: 'easy',
    title: 'Easy',
    subtitle: 'Beginner & Entry-level concepts',
    mcq: 5,
    descriptive: 5,
    badge: 'Standard',
  },
  {
    id: 'medium',
    title: 'Medium',
    subtitle: 'Mid-level technical depth & practical scenarios',
    mcq: 10,
    descriptive: 5,
    badge: 'Recommended',
  },
  {
    id: 'hard',
    title: 'Hard',
    subtitle: 'Senior & advanced architectural challenges',
    mcq: 15,
    descriptive: 10,
    badge: 'Advanced',
  },
]

export default function SelectDifficulty() {
  const navigate = useNavigate()
  const [searchParams] = useSearchParams()
  const resumeId = searchParams.get('resume_id')

  const [selected, setSelected] = useState('medium')
  const [generating, setGenerating] = useState(false)
  const [error, setError] = useState('')

  async function handleStart() {
    if (!resumeId) {
      setError('Missing resume reference. Please upload your resume first.')
      return
    }

    setGenerating(true)
    setError('')
    try {
      const res = await api.post('/interview/generate-questions', {
        resume_id: resumeId,
        difficulty: selected,
      })
      const sessionId = res.data.session_id
      navigate(`/interview/mcq?session_id=${sessionId}`)
    } catch (err) {
      setError(err.response?.data?.detail || 'Failed to generate interview questions. Please try again.')
    } finally {
      setGenerating(false)
    }
  }

  return (
    <div className="relative min-h-screen overflow-x-hidden bg-paper font-body">
      {/* faint grid overlay, same treatment as Dashboard/Login */}
      <div
        className="pointer-events-none fixed inset-0 z-0 opacity-[0.035]"
        style={{
          backgroundImage:
            'linear-gradient(#14162B 1px, transparent 1px), linear-gradient(90deg, #14162B 1px, transparent 1px)',
          backgroundSize: '46px 46px',
          maskImage: 'linear-gradient(to bottom, transparent, black 10%, black 90%, transparent)',
        }}
      />

      <div className="relative z-10">
        <DashboardHeader />

        <main className="mx-auto max-w-3xl px-6 py-12">
          <h1 className="font-display text-2xl font-bold tracking-tight text-ink">Choose Difficulty Level</h1>
          <p className="mt-1.5 text-sm text-[#4A4D68]">
            Select the intensity of your mock interview. Questions will be dynamically generated by AI
            based on your uploaded resume.
          </p>

          {error && (
            <div className="mt-6 rounded-xl border border-bad/30 bg-[#FDECEF] p-4 text-sm text-[#9B1C31]">
              {error}
            </div>
          )}

          <div className="mt-8 space-y-4">
            {LEVELS.map((level) => {
              const isSelected = selected === level.id
              return (
                <div
                  key={level.id}
                  onClick={() => setSelected(level.id)}
                  className={`cursor-pointer rounded-2xl border p-6 transition ${
                    isSelected
                      ? 'border-signal bg-[#F6F6FD] shadow-[0_14px_36px_-20px_rgba(70,64,222,0.45)] ring-1 ring-signal/30'
                      : 'border-border bg-white shadow-[0_10px_30px_-24px_rgba(20,22,43,0.25)] hover:border-signal/40'
                  }`}
                >
                  <div className="flex items-center justify-between">
                    <div className="flex items-center gap-3">
                      <div
                        className={`flex h-5 w-5 items-center justify-center rounded-full border transition ${
                          isSelected
                            ? 'border-transparent bg-gradient-to-br from-[#4640DE] to-[#3B5BDB]'
                            : 'border-[#B8BCCD] bg-white'
                        }`}
                      >
                        {isSelected && <div className="h-2 w-2 rounded-full bg-white" />}
                      </div>
                      <h3 className="font-display text-lg font-semibold text-ink">{level.title}</h3>
                      <span className="rounded border border-border bg-paper px-2 py-0.5 text-xs font-medium text-[#4A4D68]">
                        {level.badge}
                      </span>
                    </div>
                    <div className="text-right text-xs text-[#4A4D68]">
                      <span className="font-semibold text-ink">{level.mcq}</span> MCQs •{' '}
                      <span className="font-semibold text-ink">{level.descriptive}</span> Descriptive
                    </div>
                  </div>

                  <p className="mt-2 pl-8 text-sm text-[#3F4260]">{level.subtitle}</p>
                </div>
              )
            })}
          </div>

          <div className="mt-10 flex items-center justify-between">
            <button
              onClick={() => navigate('/interview/new')}
              className="rounded-lg border border-border bg-white px-4 py-2 text-sm font-medium text-ink transition hover:border-signal hover:bg-signal-soft hover:text-signal"
            >
              ← Back to Resume
            </button>
            <button
              onClick={handleStart}
              disabled={generating}
              className="rounded-lg bg-gradient-to-r from-[#4640DE] via-[#5A3FD6] to-[#3B5BDB] px-6 py-2.5 text-sm font-semibold text-white shadow-[0_10px_30px_-12px_rgba(70,64,222,0.6)] transition hover:brightness-110 disabled:opacity-50"
            >
              {generating ? 'Generating Questions with AI…' : 'Generate & Start Interview →'}
            </button>
          </div>
        </main>
      </div>
    </div>
  )
}